-- Team membership
create table if not exists team_members (
  team_id text not null,
  user_id text not null,
  email text,
  display_name text,
  role text default 'member',
  primary key (team_id, user_id)
);
alter table team_members enable row level security;
drop policy if exists "members_select" on team_members;
drop policy if exists "members_insert" on team_members;
drop policy if exists "members_update" on team_members;
drop policy if exists "members_delete" on team_members;
create policy "members_select" on team_members for select using (true);
create policy "members_insert" on team_members for insert with check (auth.uid() = user_id);
create policy "members_update" on team_members for update using (auth.role() = 'authenticated');
create policy "members_delete" on team_members for delete using (auth.role() = 'authenticated');

-- Team keypair (publicly readable for guests, only authenticated can write)
create table if not exists team_secrets (
  team_id text primary key,
