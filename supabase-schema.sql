-- Run this in your Supabase SQL Editor

-- Encrypted pins
create table if not exists encrypted_pins (
  id bigint generated by default as identity primary key,
  team_id text not null,
  pin_id uuid not null unique,
  ciphertext text not null,
  nonce text not null,
  is_public boolean default false,
  created_at timestamptz default now()
);
alter table encrypted_pins enable row level security;
drop policy if exists "open access" on encrypted_pins;
drop policy if exists "pins_select" on encrypted_pins;
drop policy if exists "pins_insert" on encrypted_pins;
drop policy if exists "pins_update" on encrypted_pins;
drop policy if exists "pins_delete" on encrypted_pins;
create policy "pins_select" on encrypted_pins for select
  using (is_public = true or auth.role() = 'authenticated');
create policy "pins_insert" on encrypted_pins for insert
  with check (auth.role() = 'authenticated');
create policy "pins_update" on encrypted_pins for update
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');
create policy "pins_delete" on encrypted_pins for delete
  using (auth.role() = 'authenticated');

